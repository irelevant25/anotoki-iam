// Writes anotoki-auth.js, the classic-script copy of anotoki-auth.mjs.
//
//     node sdk/js/build.mjs
//
// A site with no bundler and no modules (Japanese Academy loads classic scripts
// that share a global) cannot `import`. The module has exactly one export
// statement, at the bottom; this wraps the rest in a function and puts what that
// statement exported on `window.AnotokiAuth` instead. Nothing else changes, so
// the two files are the same code - run this after every edit to the .mjs and
// commit both.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
// Read as LF whatever the checkout wrote: a CRLF blank line is "\r", which the
// indenting below would turn into two spaces. Git sets the line endings.
const source = readFileSync(join(here, 'anotoki-auth.mjs'), 'utf8').replace(/\r\n/g, '\n');

const exportLine = /^export \{ createAuth, SDK_VERSION as version \};\s*$/m;
if (!exportLine.test(source)) {
  console.error('anotoki-auth.mjs: expected exactly `export { createAuth, SDK_VERSION as version };` at the end');
  process.exit(1);
}

const body = source.replace(exportLine, '').trimEnd();
const classic = `// GENERATED by sdk/js/build.mjs from anotoki-auth.mjs - edit that file, not this one.
// Classic-script build: defines window.AnotokiAuth = { createAuth, version }.
(function (global) {
  'use strict';

${body.split('\n').map((line) => (line ? '  ' + line : line)).join('\n')}

  global.AnotokiAuth = { createAuth: createAuth, version: SDK_VERSION };
})(typeof window !== 'undefined' ? window : globalThis);
`;

writeFileSync(join(here, 'anotoki-auth.js'), classic);
console.log('wrote sdk/js/anotoki-auth.js');
