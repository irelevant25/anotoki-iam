-----------------------------------------------------------
-- PROVE IT
--
-- Both languages are here and English is on; every account's language is
-- one of them, held there by the foreign key and no longer by the CHECK;
-- and every key reads in both languages - a page never shows a key, a mail
-- never goes out half in English - with as many keys as this file writes.
-----------------------------------------------------------

DO $$
DECLARE
    missing TEXT;
    keys INT;
BEGIN
    SELECT string_agg(wanted.code, ', ' ORDER BY wanted.code) INTO missing
      FROM (VALUES ('en'), ('sk')) AS wanted(code)
     WHERE NOT EXISTS (SELECT 1 FROM languages l WHERE l.code = wanted.code);
    IF missing IS NOT NULL THEN
        RAISE EXCEPTION 'languages that should be here and are not: %', missing;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM languages WHERE code = 'en' AND enabled) THEN
        RAISE EXCEPTION 'English is switched off, and every other language falls back to it';
    END IF;

    IF EXISTS (SELECT 1 FROM users u WHERE NOT EXISTS (SELECT 1 FROM languages l WHERE l.code = u.language)) THEN
        RAISE EXCEPTION 'an account has a language that is not in languages';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_constraint c
                WHERE c.conrelid = 'users'::regclass
                  AND c.contype = 'c'
                  AND c.conkey = ARRAY[(SELECT a.attnum FROM pg_attribute a
                                         WHERE a.attrelid = 'users'::regclass AND a.attname = 'language')]) THEN
        RAISE EXCEPTION 'the old CHECK on users.language should be gone: it would refuse every language added later';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint c
                    WHERE c.conrelid = 'users'::regclass
                      AND c.contype = 'f'
                      AND c.confrelid = 'languages'::regclass
                      AND c.conkey = ARRAY[(SELECT a.attnum FROM pg_attribute a
                                             WHERE a.attrelid = 'users'::regclass AND a.attname = 'language')]
                      AND c.confupdtype = 'c'
                      AND c.confdeltype = 'd') THEN
        RAISE EXCEPTION 'users.language should reference languages (code), ON UPDATE CASCADE ON DELETE SET DEFAULT';
    END IF;

    SELECT string_agg(k.name, ', ' ORDER BY k.name) INTO missing
      FROM translation_keys k
     WHERE NOT EXISTS (SELECT 1 FROM translations t WHERE t.key_name = k.name AND t.language_code = 'en')
        OR NOT EXISTS (SELECT 1 FROM translations t WHERE t.key_name = k.name AND t.language_code = 'sk');
    IF missing IS NOT NULL THEN
        RAISE EXCEPTION 'keys without an English and a Slovak string: %', missing;
    END IF;

    SELECT count(*) INTO keys FROM translation_keys;
    IF keys <> 456 THEN
        RAISE EXCEPTION 'expected 456 keys (441 of the pages, 15 of the mails), found %', keys;
    END IF;
END $$;
