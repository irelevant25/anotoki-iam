-----------------------------------------------------------
-- THE IAM'S OWN WORDS, IN THE DATABASE
--
-- What the sign-in pages, the account page and the three mails say was two
-- dictionaries compiled into the build and a file of PHP. It becomes rows:
-- a list of languages, the keys the code names, and a string per key and
-- language - so a word can be reworded in the admin console, and a language
-- added there, without a build and an upload. The admin console itself stays
-- English, written in its templates.
--
-- The tables and every string are one file on purpose. A migration applies
-- whole or not at all, and a state with the tables and no strings would put
-- keys where words should be on the sign-in page of every anotoki site.
--
-- Which keys there are is the code's business: migrations write them (this
-- one, and one for every string added later), the console only ever changes
-- a value. That is why a key has no "created by", and why a value written by
-- a migration has nobody in updated_by.
--
-- English is what every other language falls back to, string by string, so
-- it is always here and always on. A string is text and is drawn as text -
-- never HTML. What stands in for a value is a {placeholder}; which ones a
-- page key has is fixed by its English string, and which ones a mail key
-- has by the code (MAIL_KEYS in api/mail.php).
--
-- Slovak speaks to the reader informally ("ty"), as the IAM always has.
--
-- Until this file is applied the IAM runs as it did: the pages read the
-- English compiled into the build, the mails the English kept in the code,
-- and an account's language is one of the two the old CHECK allowed.
-----------------------------------------------------------

-- A code is what a browser, `ui_locales` and the `locale` claim call the
-- language ("sk", "pt-br" - always small letters here); the names are for
-- people: `name` in English for the admin console, `native_name` for the
-- chooser a visitor sees. A language switched off is no longer offered, and
-- keeps its strings.
CREATE TABLE IF NOT EXISTS languages (
    code         VARCHAR(10)   PRIMARY KEY CHECK (code ~ '^[a-z]{2}(-[a-z]{2})?$'),
    name         VARCHAR(50)   NOT NULL,                    -- in English: "Slovak"
    native_name  VARCHAR(50)   NOT NULL,                    -- as its speakers write it
    enabled      BOOLEAN       NOT NULL DEFAULT TRUE,
    sort_order   INTEGER       NOT NULL DEFAULT 0
);

-- description: where the string is shown and what its {placeholders} stand
-- for - all a translator has to go by.
CREATE TABLE IF NOT EXISTS translation_keys (
    name         VARCHAR(200)  PRIMARY KEY,
    description  TEXT,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- One string: a key in a language. There is no empty one - a language that
-- has no string for a key has no row, and reads the English. updated_by is
-- who last reworded it in the admin console; null: as a migration wrote it.
CREATE TABLE IF NOT EXISTS translations (
    key_name       VARCHAR(200)  NOT NULL REFERENCES translation_keys (name) ON UPDATE CASCADE ON DELETE CASCADE,
    language_code  VARCHAR(10)   NOT NULL REFERENCES languages (code) ON UPDATE CASCADE ON DELETE CASCADE,
    value          TEXT          NOT NULL CHECK (value <> ''),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by     INT           REFERENCES users (id) ON DELETE SET NULL,
    PRIMARY KEY (key_name, language_code)
);

