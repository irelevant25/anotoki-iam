-----------------------------------------------------------
-- AN ACCOUNT'S LANGUAGE IS ONE OF THE LANGUAGES
--
-- users.language was held to 'en' or 'sk' by a CHECK. The list is now the
-- table's, so the CHECK goes and a foreign key comes. A language deleted in
-- the admin console sends its accounts back to the column's default -
-- English, which cannot be deleted - and a code that is ever rewritten
-- takes its accounts with it.
--
-- The CHECK was written inline in 001 and never named, so it is found by
-- what it is - a check on that one column of that table - not by a guess
-- at the name PostgreSQL gave it.
-----------------------------------------------------------

DO $$
DECLARE
    old_check RECORD;
BEGIN
    FOR old_check IN
        SELECT c.conname
          FROM pg_constraint c
         WHERE c.conrelid = 'users'::regclass
           AND c.contype = 'c'
           AND c.conkey = ARRAY[(SELECT a.attnum FROM pg_attribute a
                                  WHERE a.attrelid = 'users'::regclass AND a.attname = 'language')]
    LOOP
        EXECUTE format('ALTER TABLE users DROP CONSTRAINT %I', old_check.conname);
    END LOOP;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'users'::regclass AND contype = 'f' AND confrelid = 'languages'::regclass) THEN
        ALTER TABLE users
            ADD CONSTRAINT users_language_fkey FOREIGN KEY (language) REFERENCES languages (code)
            ON UPDATE CASCADE ON DELETE SET DEFAULT;
    END IF;
END $$;

-----------------------------------------------------------
-- THE STRINGS
--
-- Every key the pages ask for (frontend/src/app/core/i18n/en.ts names them,
-- and holds the English a page falls back to while it has no strings from
-- here), and the words of the three mails, which only the server reads.
-- A test holds the two together (tests/translations.test.php): the keys of
-- en.ts are exactly the keys here without the mail ones, each English string
-- here is the one there, and the mails' English is the one in api/mail.php.
--
-- A description is all a translator has: the part of the site the string
-- belongs to and the {placeholders} it has. A page key's English string
-- fixes its placeholders - the code fills exactly those - so English may be
-- reworded in the console but never gain or lose one, and another language
-- may use only those.
--
-- A mail is put together by the server: greeting, intro, then a line that
-- is the link or the code - never part of a string - then validity and
-- ignore. So a mail's words carry no address, and the console refuses one.
--
-- Every insert steps aside for a row that is already there: a string
-- reworded in the console is the owner's and is never written over. So a
-- string added or reworded after this is a migration of its own, never an
-- edit of this file.
--
-- One string on a line, an apostrophe written twice and nothing else
-- escaped: that is all the statement splitter (api/migration_runner.php)
-- knows of a string.
-----------------------------------------------------------

